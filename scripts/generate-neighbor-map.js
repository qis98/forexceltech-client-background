const fs = require('node:fs');
const path = require('node:path');
const topojson = require('topojson-client');
const world = require('world-atlas/countries-110m.json');

const OUTPUT = path.join(__dirname, '..', 'src', 'renderer', 'vendor', 'maps', 'east-asia-neighbors.js');
const VIEW_BOUNDS = [[70, 58], [148, -5]];

const NEIGHBOR_NAMES = new Map([
  ['Afghanistan', '阿富汗'],
  ['Bangladesh', '孟加拉国'],
  ['Bhutan', '不丹'],
  ['Brunei', '文莱'],
  ['Cambodia', '柬埔寨'],
  ['India', '印度'],
  ['Indonesia', '印度尼西亚'],
  ['Japan', '日本'],
  ['Kazakhstan', '哈萨克斯坦'],
  ['Kyrgyzstan', '吉尔吉斯斯坦'],
  ['Laos', '老挝'],
  ['Malaysia', '马来西亚'],
  ['Mongolia', '蒙古'],
  ['Myanmar', '缅甸'],
  ['Nepal', '尼泊尔'],
  ['North Korea', '朝鲜'],
  ['Pakistan', '巴基斯坦'],
  ['Philippines', '菲律宾'],
  ['Russia', '俄罗斯'],
  ['South Korea', '韩国'],
  ['Tajikistan', '塔吉克斯坦'],
  ['Thailand', '泰国'],
  ['Turkmenistan', '土库曼斯坦'],
  ['Uzbekistan', '乌兹别克斯坦'],
  ['Vietnam', '越南']
]);

const geo = topojson.feature(world, world.objects.countries);
const features = geo.features
  .filter((feature) => NEIGHBOR_NAMES.has(feature.properties?.name))
  .map((feature) => ({
    ...feature,
    properties: {
      ...feature.properties,
      name: NEIGHBOR_NAMES.get(feature.properties.name),
      englishName: feature.properties.name,
      context: true
    }
  }));

const payload = {
  source: 'world-atlas@2.0.2 countries-110m, derived from Natural Earth via TopoJSON',
  license: 'ISC',
  viewBounds: VIEW_BOUNDS,
  countries: {
    type: 'FeatureCollection',
    features
  }
};

const content = `// Generated by scripts/generate-neighbor-map.js from world-atlas@2.0.2 (ISC).\nwindow.FOREXCELTECH_NEIGHBOR_GEOJSON = ${JSON.stringify(payload)};\n`;
fs.writeFileSync(OUTPUT, content, 'utf8');
console.log(`Generated ${OUTPUT} with ${features.length} neighbor countries.`);
